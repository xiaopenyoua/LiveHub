      liveHubTheme(brightness: Brightness.light);
  static final ThemeData darkTheme =
      liveHubTheme(brightness: Brightness.dark);

  /// 新代码取色入口：`AppStyle.paletteOf(context).live`。
  static LiveHubPalette paletteOf(BuildContext context) => context.lh.palette;

  static const vGap4 = SizedBox(
    height: 4,
