import 'package:flutter/material.dart';
import 'package:get/get.dart';
import 'package:livehub_ui/livehub_ui.dart';

/// LiveHub 设计体系的应用内适配层。
///
/// 颜色不再是 Material 的 seed 派生色，而是 [LiveHubPalette] 的炭灰 + 暖金
/// + 在播红。主题一律由 `livehub_ui` 的 [liveHubTheme] 构建，保证手机/桌面
/// 与 TV 端、Console 端使用同一套令牌。
class AppColors {
  static final ColorScheme lightColorScheme =
      liveHubTheme(brightness: Brightness.light).colorScheme;
  static final ColorScheme darkColorScheme =
      liveHubTheme(brightness: Brightness.dark).colorScheme;

  /// 旧接口保留：用作浅色面上的深色正文。
  /// 值等同于 [LiveHubPalette.light].text（#1A1B1F）。
  static const Color black333 = Color(0xFF1A1B1F);
}

