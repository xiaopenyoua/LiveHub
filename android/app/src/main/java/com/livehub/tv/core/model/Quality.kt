package com.livehub.tv.core.model

/**
 * 一个画质档位。
 *
 * [qn] 是**平台自己的原始码**（哔哩是 qn，别的平台没有这个概念就留 0），
 * [label] 是能上屏的名字，[resolution] 是可核对的分辨率。
 *
 * 为什么要把「码」和「名字」一起带出来：只有名字的话，排查时看不出这行字是从哪个码翻的，
 * 也判断不了「用户要的档」和「服务端给的档」是不是同一档。码在，两件事都能判。
 *
 * 为什么 [resolution] 要单列：哔哩的 `蓝光` 与 `原画` 都是 1080P，只有码和 label 区分得开；
 * 反过来 `高清` 与 `超清` 名字听着差一档，实际是 480P 与 720P。**名字是平台起的，分辨率是事实**，
 * 两者都留着，任何一处改了都不会静默变成另一种东西。
 */
data class VideoQuality(
    val qn: Int,
    val label: String,
    val resolution: String = ""
) {
    /** 平台有没有给码。`qn > 0` 才算给了；0 只可能是响应里缺字段。 */
    val known: Boolean get() = qn > 0

    /**
     * 上屏用的一行：有分辨率就「高清 480P」，没有就只写名字。
     * **名字里已经含这个分辨率时不再贴第二遍**——`15000` 是 `label="2K 极清"` + `resolution="2K"`，
     * 按「有就拼」会得到「2K 极清 2K」。去重放在这里而不是把 `resolution` 删掉：
     * 名字是平台起的（可以随时改），分辨率是事实（要留给人核），两者都不是对方的下级。
     */
    val display: String
        get() = if (resolution.isBlank() || label.contains(resolution)) label else "$label $resolution"

    companion object {
        /** 响应里没有画质字段。**不许猜一个名字填进来**——猜出来的名字就是假数据。 */
        val UNKNOWN = VideoQuality(0, "未知画质")
    }
}

/**
 * 哔哩 qn → [VideoQuality]。**全仓唯一一份表**，`ui/` 不许再抄第二张。
 *
 * 数值不是猜的，也不是从旧代码抄的：它们逐条来自**平台自己在取流响应里返回的
 * `playurl_info.playurl.g_qn_desc`**（实测 2026-10-29，匿名请求，房间 7734200，
 * 请求参数 `qn=10000`，响应 `current_qn=150`、`accept_qn=[15000,10000,400,250,150]`）：
 *
 * | qn | 平台 desc | 平台 brief_desc |
 * |---|---|---|
 * | 80 | 流畅 | — |
 * | 150 | 高清 | 480P |
 * | 250 | 超清 | 720P |
 * | 400 | 蓝光 | 1080P |
 * | 10000 | 原画 | 1080P |
 * | 15000 | 2K 极清 | 2K |
 * | 20000 | 4K | — |
 * | 30000 | 杜比 | — |
 *
 * **复算这张表的口径（三条，缺一条数就对不上）**：
 * 1. 取值在 `stream[].format[].codec[].current_qn`，**三层**，`playurl` 顶层没有这个字段；
 *    `accept_qn` 同样挂在 codec 行上。
 * 2. 同一次响应里不同 codec 的 `current_qn` 可以不同：那次带 `codec=0,1` 请求时
 *    avc 行 = 150、hevc 行 = 250。所以「本次响应的 current_qn」记成集合时，混的是
 *    **两个 codec**，不是两条流。（本仓只请求 `codec=0`，只播 avc。）
 * 3. 签发值不是「匿名恒等于某个数」：2026-10-29 匿名扫活跃房，其中就有直接给 10000（原画）的。
 *    **这里不许写比例**：同一天重扫一次，落到 250 与 10000 的房间数就变了——那不是分布，
 *    是那一次的属性。要证伪「匿名一律压到 250」，**一个反例就够**，而一个反例数得出来。
 *
 * **这里曾经错了两档**：旧实现把 150 叫「流畅」、250 叫「高清」，也就是把 480P 说成流畅、
 * 把 720P 说成高清——**用户屏幕上那句「流畅」比实际画质低了一档**。低报也是谎，
 * 只是方向没人愿意相信。判据不是「我觉得 150 该叫什么」，是平台自己那张 `g_qn_desc`。
 *
 * 为什么不每次现读 `g_qn_desc`：那张表在一次响应里，UI 要在没有网络时也能把上一帧的名字
 * 重新画出来（切线路、重连、错误页），所以名字必须能在本地算。代价写在这里：
 * **哔哩改档位名时，要改的是这一处。**
 *
 * 登录态不需要第二张表：登录变的只是 `current_qn` 的**取值**（同一个房间的上限被抬高），
 * 码到名字的对应关系一个字都不变。反过来也别指望「匿名一定是低档」——匿名房里有的是原画。
 */
fun bilibiliQuality(qn: Int): VideoQuality = when (qn) {
    80 -> VideoQuality(80, "流畅")
    150 -> VideoQuality(150, "高清", "480P")
    250 -> VideoQuality(250, "超清", "720P")
    400 -> VideoQuality(400, "蓝光", "1080P")
    10000 -> VideoQuality(10000, "原画", "1080P")
    15000 -> VideoQuality(15000, "2K 极清", "2K")
    20000 -> VideoQuality(20000, "4K")
    30000 -> VideoQuality(30000, "杜比")
    // 未知码保留原始值，名字只写码：编一个名字出来会让「平台新加了档位」变成静默错标
    else -> if (qn > 0) VideoQuality(qn, "qn$qn") else VideoQuality.UNKNOWN
}
