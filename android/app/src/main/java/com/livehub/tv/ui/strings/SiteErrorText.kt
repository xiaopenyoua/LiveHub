package com.livehub.tv.ui.strings

import com.livehub.tv.core.model.SiteError

/**
 * `SiteError` → 屏上那一句中文。**全工程唯一的一张表**。
 *
 * 为什么必须只有一张：同一个码在两处各写一句，改文案的人只会改他看见的那一份，而
 * **两份都读得通**——没人能判断哪句是现役，于是真源就没了。这和「虎牙两处都叫
 * `liveStatus`」是同一个形状：不是谁写错了，是并存之后就没有真源。
 *
 * 四条文案纪律，改任何一行都要同时满足 1–3，且第 4 条必须跨文件对得上：
 * 1. **不出现英文码**。用户不该看到 `PARSE_BROKEN`、`SIGN_INVALID` 这种词——那是我们
 *    内部的分类法，不是他的语言。
 * 2. **不提状态码**。`HTTP 403` / `status_code=10011` 对用户没有可执行含义，它们是
 *    诊断页的证据，不是屏上的说明。
 * 3. **不甩锅给用户**。`retryable = false && report = false` 的码（房间号贴错、下播、
 *    识别不出）是我们陪着用户一起看的口吻；`report = true` 的码是我们自己认账
 *    「没读懂 / 接口可能改版」，因为那确实是我们该修的东西。
 * 4. **文案里出现「再试 / 稍后再试 / 等一下再试」的码，`SiteError.retryable` 必须是
 *    `true`。** 反过来（`retryable = true` 但文案没提重试）不算错，只算少说了一句。
 *    这条比上面三条更容易被违反，因为它要求**跨文件一致**，而且违反之后两处单独看都对：
 *    我们内部判「重试没用」而屏上劝人再试，用户照做、拿到一模一样的结果——第二次的
 *    失望比第一次重。**文案和行为对不上，是这类系统里最难被发现的谎。**
 *    `HTTP_4XX` 就是这条的活标本：它的 `retryable` 该是 `false`（backend 正在改），
 *    所以那一句里不许出现「再试」。
 *
 * 这里的 `when` **13 个码全列、故意不写 `else`**。这是整个错误码体系里唯一能让
 * 「将来加了第 14 个码时编译器报错」的位置：加码的人被迫在这一刻写一句人话，
 * 而不是让新码默默落到一句泛泛的兜底文案里。**谁加 `else` 谁就把这道闸门废了。**
 */
fun SiteError.userText(): String = when (this) {

    // ── 网络的错：动作是「等一会儿 / 换个网络再试」 ───────────────────────────
    SiteError.NET_OFFLINE -> "网络好像断开了，检查一下网络再试"
    SiteError.NET_TIMEOUT -> "连接超时了，网络可能不太稳，稍后再试"

    // ── 平台的错：原样告诉用户「那边有问题」，不说得比事实更严重 ─────────────
    //
    // `HTTP_4XX` 的文案**故意不提「再试」**：4xx 重试一百次还是 4xx（参数错、路径错、
    // 权限错），它的 `retryable` 该是 `false`（backend 正在改）。屏上要是劝人再试，
    // 用户照做、拿到一模一样的结果——第二次的失望比第一次重。
    SiteError.HTTP_4XX -> "平台这次没给到内容，先看看别的"
    SiteError.HTTP_5XX -> "平台那边出了点问题，稍后再试"
    SiteError.RATE_LIMITED -> "请求太频繁被平台暂时限流了，等一会儿再试"

    // ── 我们的错：认账。这两类上报优先级最高，是平台改版最早的信号 ────────────
    SiteError.SIGN_INVALID -> "平台的取流校验变了，我们这边要跟进修，稍后再试"
    SiteError.PARSE_BROKEN -> "我们没读懂平台的返回，接口可能已改版"

    // ── 用户手上的信息不对：陪着他一起看，不指责 ──────────────────────────────
    //
    // 这两条**必须一眼分得开**，因为它们对用户是两个动作：
    // - ROOM_NOT_FOUND：房间确实没了（平台明确说这个号不存在）→ 他该去核对房间号；
    // - ID_UNRESOLVED：我们没能把他的输入定位成房间（粘短链、少打几位）→ 他该换一种
    //   入口打开，而不是继续在输入框里改数字。
    // 所以两条的主语故意不同：一条是「平台上查不到」，一条是「没能定位到」。
    SiteError.ROOM_NOT_FOUND -> "平台上查不到这个直播间，房间号可能贴错了"
    SiteError.ID_UNRESOLVED -> "没能从你给的这个号定位到直播间，从首页或搜索打开更稳"

    // ── 房间本身的状态：不是故障，是事实 ─────────────────────────────────────
    SiteError.STREAM_OFFLINE -> "这个直播间当前没有开播"

    // ── 设备与地区：给出唯一的出路，不让他反复重试 ────────────────────────────
    SiteError.GEO_BLOCKED -> "这个直播在你所在的地区看不到"
    SiteError.DECODE_UNSUPPORTED -> "这个画面当前设备解不了，可以去设置里打开强制 H.264"

    // ── 弹幕：单独一条，因为它不该让人以为画面也没了 ──────────────────────────
    // `retryable = true`（会自动重连），所以这里可以承诺「会自动重连」——
    // 又是一个文案必须和字段对齐的地方。
    SiteError.DANMAKU_PROTOCOL -> "弹幕连不上了，会自动重连，画面不受影响"
}
